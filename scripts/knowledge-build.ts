/**
 * Regenerates the local knowledge fallback from knowledge/**.
 * Usage: npm run knowledge:build
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { buildBuiltinKnowledge } from "../src/services/knowledge/builtin-source";
import { repositoryKnowledgeRoot } from "../src/services/knowledge/ingest";

const target = fileURLToPath(new URL("../src/services/knowledge/builtin-knowledge.ts", import.meta.url));

async function main() {
  const records = await buildBuiltinKnowledge(repositoryKnowledgeRoot());
  const body = [
    "// AUTO-GENERATED by scripts/knowledge-build.ts from knowledge/**/*.{md,json}.",
    "// Do not edit by hand; run `npm run knowledge:build`.",
    'import type { TravelKnowledgeRecord } from "./types";',
    "",
    `export const BUILTIN_KNOWLEDGE: TravelKnowledgeRecord[] = ${JSON.stringify(records, null, 2)};`,
    "",
  ].join("\n");
  await writeFile(target, body, "utf8");
  process.stdout.write(`knowledge: wrote ${records.length} records to ${path.relative(process.cwd(), target)}\n`);
}

main().catch((error) => {
  process.stderr.write(`knowledge build failed: ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
